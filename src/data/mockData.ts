// Helper to generate 30 days of snapshots
function generateSnapshots(
  basePrice: number,
  baseSold: number,
  basePopularity: number,
  trendDirection: 'up' | 'down' | 'stable' | 'new',
  commissionRate: number
) {
  const snapshots = [];
  const now = new Date('2026-11-07T00:00:00Z');

  for (let i = 30; i >= 0; i--) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];

    let factor = 1;
    if (trendDirection === 'up') {
      // Growing steadily from 30 days ago to now
      factor = 0.65 + ((30 - i) / 30) * 0.45;
    } else if (trendDirection === 'down') {
      factor = 1.25 - ((30 - i) / 30) * 0.35;
    } else if (trendDirection === 'new') {
      // First 20 days had almost no data
      factor = i > 7 ? 0 : 0.4 + ((7 - i) / 7) * 0.6;
    } else {
      factor = 0.95 + (Math.sin(i) * 0.08);
    }

    const dayPrice = Math.round(basePrice * (1 + (Math.cos(i) * 0.02)));
    const daySold = Math.max(10, Math.round(baseSold * factor));
    const dayPop = Math.min(100, Math.max(20, Math.round(basePopularity * factor)));

    snapshots.push({
      date: dateStr,
      price: dayPrice,
      soldCount: daySold,
      popularityScore: dayPop,
      rating: 4.8,
      reviewCount: Math.round(daySold * 0.22),
      commissionRate,
    });
  }

  return snapshots;
}

